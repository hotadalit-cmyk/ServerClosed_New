export function surfaceRegionById(id: string): WorldRegionDef | null {
  return SURFACE_REGIONS.find((r) => r.id === id) ?? null;
}
export function worldRegionById(id: string): WorldRegionDef | null {
  return ALL_WORLD_REGIONS.find((r) => r.id === id) ?? null;
}

/** К какому поверхностному региону принадлежит точка: ближайший центр (арены не изолированы — переходные экотоны). */
export function regionAt(x: number, y: number): WorldRegionDef {
  let best = SURFACE_REGIONS[0];
  let bestD = Infinity;
  for (const r of SURFACE_REGIONS) {
    const d = (r.center.x - x) ** 2 + (r.center.y - y) ** 2;
    if (d < bestD) { bestD = d; best = r; }
  }
  return best;
}

/** Подземный регион, которому соответствует активное подземелье (для открытия карты). */
export function dungeonRegionId(id: string): string {
  if (id === 'catacombs') return 'root_garden';
  if (id === 'crystal_caves') return 'forgotten_vein';
  if (id === 'underground_channel') return 'underground_channel';
  if (id === 'birth_nest') return 'quiet_cradle'; // родовая норка — колыбель души
  return 'underground_channel';
}

