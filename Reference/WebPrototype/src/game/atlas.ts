export type WorldLayer = 'surface' | 'underground' | 'depths';

export interface WorldRegionDef {
  id: string;
  name: string;
  layer: WorldLayer;
  /** Центр зоны на ИГРОВОЙ карте 52×52 (для surface). Underground/depths — схема для атласа. */
  center: { x: number; y: number };
  /** Радиус зоны для раскраски атласа/карты (regionAt работает по ближайшему центру). */
  r: number;
  difficulty: string;
  /** Экологическая функция (п.10.1) — почему регион существует. */
  ecology: string;
  desc: string;
  /** Запечатанные области Глубин (Этап 4) помечены — на карте не открываются. */
  sealed?: boolean;
}

